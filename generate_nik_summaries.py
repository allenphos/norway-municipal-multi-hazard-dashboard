"""Generate NIK 2026 municipality summaries ONCE and cache them in CSV.

Inputs (from the final notebook):
  results/mhi_pipeline_final_355.csv
  results/municipality_explanations_final.csv
Output (read-only in the Streamlit app):
  results/municipality_llm_summaries_final.csv

API billing occurs ONLY while this script runs. It checkpoints after every
successful response and resumes without charging again for unchanged rows.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import pandas as pd

from nik_feature_labels import humanize_feature_text

DEFAULT_MODEL = "gpt-5.4-mini"  # Same model configured in the existing dashboard
PROMPT_VERSION = "nik-2026-shap-v2-human-readable"
PREVIOUS_PROMPT_VERSION = "nik-2026-shap-v1"
OUTPUT_COLUMNS = [
    "kommunenummer", "kommunenavn", "llm_summary", "generation_model",
    "prompt_version", "input_hash", "generated_at",
    "landslide_prob_noflood_source", "flood_permille_final_source",
    "mhi_source", "top_positive_shap_source", "top_negative_shap_source",
]


def normalize_ids(frame: pd.DataFrame) -> pd.DataFrame:
    result = frame.copy()
    if "kommunenummer" not in result:
        raise ValueError("Missing kommunenummer")
    result["kommunenummer"] = (
        result["kommunenummer"].astype("string").str.strip()
        .str.replace(r"\.0$", "", regex=True).str.zfill(4)
    )
    if result["kommunenummer"].isna().any() or result["kommunenummer"].duplicated().any():
        raise ValueError("Missing or duplicate municipality IDs")
    return result


def read_inputs(root: Path) -> pd.DataFrame:
    data_path = root / "results/mhi_pipeline_final_355.csv"
    shap_path = root / "results/municipality_explanations_final.csv"
    for path in (data_path, shap_path):
        if not path.exists():
            raise FileNotFoundError(f"Required file missing: {path}")
    final = normalize_ids(pd.read_csv(data_path, dtype={"kommunenummer": "string"}))
    explanations = normalize_ids(pd.read_csv(shap_path, dtype={"kommunenummer": "string"}))
    required_final = {"kommunenummer", "kommunenavn", "landslide_prob_noflood", "flood_permille_final", "mhi"}
    required_expl = {"kommunenummer", "top_positive_shap", "top_negative_shap"}
    if required_final - set(final):
        raise ValueError(f"Missing final result columns: {sorted(required_final - set(final))}")
    if required_expl - set(explanations):
        raise ValueError(f"Missing SHAP columns: {sorted(required_expl - set(explanations))}")
    if len(final) != 355 or len(explanations) != 355:
        raise ValueError(f"Expected 355 modelled municipalities, got {len(final)} and {len(explanations)}")
    if set(final["kommunenummer"]) != set(explanations["kommunenummer"]):
        raise ValueError("Municipality IDs in final and SHAP exports do not match")
    joined = final[list(required_final)].merge(
        explanations[["kommunenummer", "top_positive_shap", "top_negative_shap"]],
        on="kommunenummer", how="inner", validate="one_to_one",
    )
    for col in ("landslide_prob_noflood", "flood_permille_final", "mhi"):
        joined[col] = pd.to_numeric(joined[col], errors="raise")
    if joined[["landslide_prob_noflood", "flood_permille_final", "mhi"]].isna().any().any():
        raise ValueError("Numerical values are missing in final data")
    if not joined["landslide_prob_noflood"].between(0, 1).all() or not joined["mhi"].between(0, 1).all():
        raise ValueError("Landslide probabilities or MHI are outside [0, 1]")
    if (joined["flood_permille_final"] < 0).any():
        raise ValueError("Flood exposure cannot be negative")
    return joined.sort_values("kommunenummer").reset_index(drop=True)


def row_payload(row: pd.Series) -> dict[str, Any]:
    return {
        "kommunenummer": str(row["kommunenummer"]),
        "kommunenavn": str(row["kommunenavn"]),
        "landslide_prob_noflood": float(row["landslide_prob_noflood"]),
        "flood_permille_final": float(row["flood_permille_final"]),
        "mhi": float(row["mhi"]),
        "top_positive_shap": "" if pd.isna(row["top_positive_shap"]) else str(row["top_positive_shap"]),
        "top_negative_shap": "" if pd.isna(row["top_negative_shap"]) else str(row["top_negative_shap"]),
    }


def fingerprint(payload: dict[str, Any], model: str, prompt_version: str = PROMPT_VERSION) -> str:
    serialized = json.dumps(
        {"model": model, "prompt_version": prompt_version, "data": payload},
        sort_keys=True, ensure_ascii=False, separators=(",", ":"),
    )
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


def base_summary(payload: dict[str, Any]) -> str:
    # All numeric content is deterministic, never generated by a language model.
    return (
        f"{payload['kommunenavn']} has a model-estimated shallow-landslide screening value "
        f"of {payload['landslide_prob_noflood']:.3f}, mapped flood-zone exposure of "
        f"{payload['flood_permille_final']:.3f}‰ of municipal area, and a relative "
        f"multi-hazard index of {payload['mhi']:.3f}."
    )


def build_request(payload: dict[str, Any]) -> str:
    return json.dumps({
        "municipality": payload["kommunenavn"],
        "positive_contributors_to_separate_uncalibrated_HGB": humanize_feature_text(payload["top_positive_shap"]),
        "negative_contributors_to_separate_uncalibrated_HGB": humanize_feature_text(payload["top_negative_shap"]),
    }, ensure_ascii=False)


API_INSTRUCTIONS = """You write ONE short English sentence for a public-facing Norwegian municipality research dashboard.
Explain only the supplied positive/negative SHAP contributors to a SEPARATELY TRAINED UNCALIBRATED HistGradientBoosting model's output.
Use no external facts. Never imply that SHAP explains the separate calibrated probability displayed in the dashboard.
Never describe features as proven causes or claim a future landslide will occur.
Use only the supplied natural-language feature descriptions. Keep direction correct: positive increases the separate uncalibrated model output, negative decreases it.
No made-up numbers, no risk forecasts, no qualitative rankings, no mentions of annual probabilities.
Use clear everyday English rather than codes or abbreviations (never write feature identifiers with underscores). Keep it understandable for nontechnical readers, without adding physical explanations not supported by the feature labels. Maximum 45 words.
Return ONLY valid JSON: {"factor_sentence": "..."}.
"""


def get_factor_sentence(client, payload: dict[str, Any], model: str) -> str:
    response = client.responses.create(
        model=model,
        instructions=API_INSTRUCTIONS,
        input=build_request(payload),
        max_output_tokens=250,
    )
    raw = response.output_text.strip()
    try:
        result = json.loads(raw)
        sentence = result["factor_sentence"].strip()
    except (json.JSONDecodeError, KeyError, AttributeError) as exc:
        raise ValueError(f"Unexpected API output for {payload['kommunenummer']}: {raw[:180]!r}") from exc
    sentence = humanize_feature_text(sentence)  # Safety net if the API echoes codes.
    if not sentence or len(sentence) > 420 or "\n" in sentence:
        raise ValueError(f"Invalid factor sentence for {payload['kommunenummer']}")
    if not sentence.endswith((".", "!")):
        sentence += "."
    return sentence


def load_api_key(root: Path) -> str | None:
    key = os.getenv("OPENAI_API_KEY")
    if key:
        return key
    # Compatibility with the user's existing local creds.json; never commit this file.
    path = root / "creds.json"
    if path.exists():
        content = json.loads(path.read_text(encoding="utf-8"))
        return content.get("OPENAI_API_KEY")
    return None


def existing_rows(path: Path) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    old = normalize_ids(pd.read_csv(path, dtype={"kommunenummer": "string"}, keep_default_na=False))
    if not set(OUTPUT_COLUMNS).issubset(old.columns):
        raise ValueError(f"Existing summary CSV has an unexpected format: {path}. Back it up and fix it before continuing.")
    return {str(r["kommunenummer"]): r.to_dict() for _, r in old.iterrows()}


def write_checkpoint(path: Path, saved: dict[str, dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    table = pd.DataFrame(list(saved.values()), columns=OUTPUT_COLUMNS)
    if not table.empty:
        table = table.sort_values("kommunenummer")
    tmp = path.with_suffix(".csv.tmp")
    table.to_csv(tmp, index=False)
    os.replace(tmp, path)


def build_record(payload: dict[str, Any], summary: str, model: str, hash_value: str) -> dict[str, Any]:
    return {
        "kommunenummer": payload["kommunenummer"],
        "kommunenavn": payload["kommunenavn"],
        "llm_summary": summary,
        "generation_model": model,
        "prompt_version": PROMPT_VERSION,
        "input_hash": hash_value,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "landslide_prob_noflood_source": payload["landslide_prob_noflood"],
        "flood_permille_final_source": payload["flood_permille_final"],
        "mhi_source": payload["mhi"],
        "top_positive_shap_source": payload["top_positive_shap"],
        "top_negative_shap_source": payload["top_negative_shap"],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent, help="Project root directory")
    parser.add_argument("--model", default=DEFAULT_MODEL, help="OpenAI model ID")
    parser.add_argument("--limit", type=int, help="Generate at most this many NEW summaries")
    parser.add_argument("--all", action="store_true", help="Explicitly generate all missing/changed summaries")
    parser.add_argument("--dry-run", action="store_true", help="Report work without any API calls")
    parser.add_argument("--force", action="store_true", help="Regenerate summaries even when input hash matches")
    args = parser.parse_args()
    root = args.root.resolve()
    if not args.dry_run and not args.all and args.limit is None:
        parser.error("Choose --limit 3 for a small test, or --all to generate all 355 once")
    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be at least 1")
    rows = read_inputs(root)
    output = root / "results/municipality_llm_summaries_final.csv"
    saved = existing_rows(output)
    work = []
    reused = 0
    converted = 0
    changed_cache = False
    for _, row in rows.iterrows():
        payload = row_payload(row)
        digest = fingerprint(payload, args.model)
        prior = saved.get(payload["kommunenummer"])
        if not args.force and prior and prior.get("input_hash") == digest and prior.get("llm_summary"):
            # Also repair a cached response if its text was saved before
            # natural-language labels were introduced.
            new_text = humanize_feature_text(prior["llm_summary"])
            if new_text != prior["llm_summary"]:
                prior["llm_summary"] = new_text
                saved[payload["kommunenummer"]] = prior
                changed_cache = True
            reused += 1
        elif (not args.force and prior and prior.get("prompt_version") == PREVIOUS_PROMPT_VERSION
              and prior.get("generation_model") == args.model
              and prior.get("input_hash") == fingerprint(payload, args.model, PREVIOUS_PROMPT_VERSION)
              and prior.get("llm_summary")):
            # Convert previously paid-for v1 responses to readable labels
            # locally, without calling the API again. Preserve provenance.
            prior["llm_summary"] = humanize_feature_text(prior["llm_summary"])
            prior["prompt_version"] = "nik-2026-shap-v1-display-translated"
            prior["input_hash"] = digest
            saved[payload["kommunenummer"]] = prior
            reused += 1
            converted += 1
            changed_cache = True
        else:
            work.append((payload, digest))
    if changed_cache and not args.dry_run:
        write_checkpoint(output, saved)
    print(f"Total municipalities: {len(rows)} | already cached: {reused} | to generate: {len(work)}")
    if converted:
        print(f"Updated {converted} old cached summaries with readable labels without API calls.")
    print(f"Output: {output}")
    if args.dry_run or not work:
        return

    api_key = load_api_key(root)
    if not api_key:
        raise RuntimeError("Missing OPENAI_API_KEY environment variable or local creds.json")
    from openai import OpenAI
    client = OpenAI(api_key=api_key, timeout=45.0, max_retries=2)
    work_limit = len(work) if args.all and args.limit is None else min(len(work), args.limit or len(work))
    for i, (payload, digest) in enumerate(work[:work_limit], start=1):
        try:
            sentence = get_factor_sentence(client, payload, args.model)
        except Exception as exc:
            print(f"Stopped on {payload['kommunenummer']} ({payload['kommunenavn']}): {exc}")
            print("Already generated summaries have been preserved; rerun to resume.")
            raise
        summary = base_summary(payload) + " " + sentence
        saved[payload["kommunenummer"]] = build_record(payload, summary, args.model, digest)
        write_checkpoint(output, saved)
        print(f"[{i}/{work_limit}] Saved {payload['kommunenummer']} {payload['kommunenavn']}")
        if i <= 3:
            print("  Preview:", summary)
    print(f"Done. Generated {work_limit} in this run; rerun with --all to complete the rest.")


if __name__ == "__main__":
    main()
